-- «المدينة» — تحت المحافظة، في الأونبوردينج وفي «بياناتك».
--
-- «القاهرة» لوحدها ما بتقولش للأدمن الطالب في مدينة نصر ولا في حلوان، ولا
-- بتفرّق بين طالبين اسمهم واحد في نفس المحافظة لما ولي أمر يتصل.
--
-- ## رقم، مش اسم
--
-- `city_id` هو رقم المدينة في `packages/contracts/src/cities.ts`. الأرقام دي
-- بتاعة المصدر ومش بتتغيّر، فالرقم المتخزّن بيفضل يعني نفس المكان حتى لو
-- الاسم اتصلّح.
--
-- ## ليه مفيش جدول `cities` ولا FK
--
-- القايمة ثابتة في الكود، والتحقق إن المدينة تبع المحافظة بيحصل في
-- `OnboardingSchema` — والـAPI بيتحقق بنفس السكيما بالظبط. جدول مرجعي كان
-- هيتملّى من الـseed، والـseed على كل boot **مش قاتل** لو وقع: يبقى على ستاك
-- مدرّس جديد الجدول فاضي، والـFK يرفض كل تسجيل جديد.
--
-- ## ليه nullable
--
-- كل طالب اتسجّل قبل كده ما اتسألش. اختراع إجابة ليه يبقى البروفايل بيدّعي
-- حاجة محدش قالها — نفس منطق `school_stream`. الفورم بيطلبها من دلوقتي،
-- واللي عنده null هيتسأل أول ما يحفظ «بياناتك».
