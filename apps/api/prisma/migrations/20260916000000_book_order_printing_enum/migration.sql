-- ## ليه ده status مش عمود boolean
--
-- اليوم فيه تسليمتين مختلفتين: الورق بيروح للمطبعة، والكرتونة بتروح لشركة
-- الشحن. الاتنين كانوا بيتلموا في ضغطة واحدة اسمها «اتشحن»، والتمن إن تبويب
-- «مدفوعة» ما كانش يقدر يجاوب على السؤال الوحيد اللي بيتسأل كل صبح: مين فيهم
-- بعتّه المطبعة خلاص. عمود boolean جنب `shipped_at` كان هيسيب السؤال ده لفلتر
-- محدش هيبنيه؛ الـstatus بيحطه في بار التبويبات مكان الشغل.
--
-- ⚠️ ومش محطة إجبارية: `markShipped` لسه بيقبل `paid` على طول — نسخة واحدة
-- بتتسلّم على الكاونتر ما بتعديش على طبعة أصلاً، وإجبار «راح للمطبعة» عشان
-- يفتح «اتشحن» معناه إني أكتب كذبة في الـaudit عشان أرضّي state machine. نفس
-- الحجة اللي `markDelivered` بيقولها من زمان لما بيقبل `paid` من غير `shipped`.
--
-- ## ليه الملف ده لوحده
--
-- Postgres ما بيسمحش تستخدم قيمة enum في نفس الـtransaction اللي ضافتها، و
-- Prisma بيشغّل كل ملف migration في transaction واحدة. فالعمود اللي جاي في
-- `20260916000100_book_order_printed_at` لازم يبقى في ملف تاني. نفس السبب اللي
-- خلّى `20260904120000_book_order_lifecycle_enums` مقسومة على ملفين.
--
-- `AFTER 'paid'` عشان ترتيب الـenum يفضل هو ترتيب الشغل نفسه — أي `ORDER BY
-- status` بيطلع الليستة بالترتيب اللي الطلب بيمشي بيه.
--
