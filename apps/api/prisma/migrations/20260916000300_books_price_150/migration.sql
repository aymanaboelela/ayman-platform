-- ## ليه الرقم نازل، وده مش غلطة
--
-- كتب تانية بكالوريا كانت ٢٥٠، وكتابين أولى اتضافوا في
-- `20260916000200_year1_books` بـ٢٥٠ عشان يبقوا زيهم. القرار اتغيّر بعدها
-- بدقايق: السعر الموحّد بقى ١٥٠ والفرق راح على الشحن، اللي بقى على حسب
-- المحافظة (٨٠ / ١٠٠ / ١٥٠) بدل رقم واحد ثابت. فالملف ده بيساوي الرف كله على
-- الرقم الجديد بدل ما يعدّل migration اتطبّقت خلاص — تعديلها بيغيّر الـchecksum
-- و`migrate deploy` بترفض تشتغل على أي داتابيز شغّالتها قبل كده.
--
-- ## الطلبات القديمة ما بتتلمسش
--
-- ولا صف واحد في `book_order_items` بيتغيّر. `unit_price_cents` snapshot
-- متجمّد يوم الطلب — ده كل سبب وجوده — و`book_orders.amount_cents` هو اللي
-- الطالب وافق عليه وحوّل بيه فعلاً. تنزيل السعر على الطلبات القديمة معناه إن
-- إيرادات شهر قفل يتعاد كتابتها من غير أي صف يفسّر الفرق.
--
-- ## `compare_price_cents`
--
-- `books_compare_price_above_price` بيمنع «سعر قبل الخصم» يبقى أقل من أو يساوي
-- السعر — لأنه بيرسم خصم وهمي. أي قيمة كانت فوق ٢٥٠ وبقت تحت ١٥٠ هتكسر الـCHECK
-- وتوقّع الـmigration، فبتتمسح. المسح هنا مقصود: «٢٠٠ بدل ١٥٠» خصم حقيقي
-- ويفضل، و«١٠٠ بدل ١٥٠» مش خصم أصلاً.
--
-- ⚠️ الترتيب مهم — المسح قبل الـUPDATE، عشان الـCHECK بيتقيّم على صف بعد
-- التعديل والاتنين في نفس الـtransaction.
--
-- ## والعمودين القدام على `courses`
--
-- `book_price_cents` هو الفرع القديم اللي `courseBook()` بيقع عليه لو صف
-- الكتالوج مش `is_active`. سايبه على ٢٥٠ معناه إن كورس واحد يتشال كتابه من
-- الرف يبدأ يبيع بالسعر القديم من غير ما حد يلاحظ.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE "app"."books"
   SET "compare_price_cents" = NULL
 WHERE "compare_price_cents" IS NOT NULL
   AND "compare_price_cents" <= 15000;

UPDATE "app"."books"
   SET "price_cents" = 15000,
       "updated_at"  = now()
 WHERE "price_cents" <> 15000;

UPDATE "app"."courses"
   SET "book_price_cents" = 15000
 WHERE "book_price_cents" IS NOT NULL
   AND "book_price_cents" <> 15000;
