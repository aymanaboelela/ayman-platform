-- صورة لوحة الشرف — الصورة الوحيدة اللي مسموح تتنشر للطالب.
--
-- اللوحة على الصفحة الرئيسية بتتقري من أي حد على الإنترنت، وبتقول اسم طالب
-- قاصر. عشان كده الصورة اللي بتظهر جنب الاسم لازم تبقى قرار مستقل: المدرّس هو
-- اللي بيحطها، للوحة دي بالذات.
--
-- ## ليه مش `users.image`
--
-- العمود ده أڤاتار الطالب نفسه — صورة چوجل اللي جات مع تسجيل الدخول، أو صورة
-- رفعها هو لشاشة مابيشوفهاش غيره والمدرّس. لو اللوحة قرت منه، أول طالب يتحط
-- عليها وعنده صورة چوجل بتبقى وشّه اتنشر على النت من غير ما حد يقرر ده.
-- الكود كان بيرفض يعرض الأڤاتار أصلاً للسبب ده (`honor-board-section.tsx`)،
-- والعمود ده هو اللي بيخلّي «آه، الصورة دي» جملة يقدر يقولها.
--
-- ## مفتاح تخزين، مش لينك
--
-- `ab/abcd….webp`. أصل الوسائط بيتركّب وقت العرض (`mediaUrl()`)، وكتابة الأصل
-- الحالي جوه صف بتحوّل نقل الاستضافة لميجريشن داتا.
