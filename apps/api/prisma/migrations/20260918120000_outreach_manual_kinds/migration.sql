-- ## ليه دول جوه نفس الـenum بتاع الرسايل الأوتوماتيك
--
-- الأربعة اللي فوق بيبعتهم `OutreachSweeper` لوحده: cron بيلاقي حاجة بقت
-- صحيحة ويكتب عنها. الاتنين دول العكس — شاشة `/admin/follow-up` وطالب
-- بالاسم ودوسة زرار. ومع ذلك مكانهم هنا مش على مسار `sendManual` اللي
-- `/admin/broadcast` بيستعمله، لسببين الجدول ده هو اللي بيوفرهم:
--
--   · `dedupe_key` — «ابعت للكل» اتداست مرتين ما تكتبش نفس الرسالة مرتين.
--   · `variant_key` — أربعين طالب في دوسة واحدة ما يقروش نفس الجملة.
--
-- من غير الاتنين دول الفيتشر بيبقى mailing list بيلبس اسم حد.
--
-- ## ليه الملف ده لوحده ومفيهوش غير ALTER TYPE
--
-- Postgres ما بيسمحش تستخدم قيمة enum في نفس الـtransaction اللي ضافتها،
-- وPrisma بيشغّل كل ملف migration في transaction واحدة. مفيش عمود ولا index
-- جديد هنا أصلاً — الرسايل دي بتتكتب في نفس `outreach_messages` وبنفس
-- الأعمدة — فالملف ده بيفضل سطرين، ولو احتاج حاجة تستعمل القيم دي هتيجي في
-- ملف بعده. نفس السبب اللي قسم `20260916000000_book_order_printing_enum`.
--
-- ⚠️ الترتيب مهم: الشاشة بترسم الـkinds بترتيب `OUTREACH_KINDS`، والاتنين دول
-- آخر حاجة عشان التبويبات تفضل زي ما هي.
