-- «حطهالي في مكان لسه متأكدش منه عشان أقبلهم بنفسي».
--
-- الطلب اللي قراية إيصاله بتقول إن فيه حاجة غلط بيفضل `paid` — الفلوس اتقالت
-- والطالب شايف «بنجهّزه» — بس بيتعلّم محجوز، وبيختفي من قايمة الطباعة ومن
-- أزرار الشحن بالجملة لحد ما أيمن يبصّله بنفسه.
--
-- ## ليه علامة مش حالة جديدة
--
-- `status` هو اللي بيبني كل تبويب وكل فلتر وكل تصدير وكشف التعبئة. حالة سادسة
-- كانت هتخلي كل استعلام في المنيول يتراجع، وأول واحد يتنسي بيبقى طلب بيتشحن
-- من غير ما حد بصّله — وده بالظبط اللي العمود ده موجود يمنعه.
--
-- والعلامة بتقول حاجة تانية غير الحالة: «ده مدفوع، بس المبلغ اللي مكتوب على
-- الإيصال أقل من المطلوب». الاتنين حقيقة مستقلة عن التانية.
--
-- ## سببين، والاتنين من قراية الإيصال
--
--   amount_short      — المبلغ المقروء من الصورة أقل من `amount_cents`.
--                       ده اللي أيمن طلبه بالنص: «أهم حاجة الرقم ما يبقاش أقل
--                       من الرقم الموجود».
--   duplicate_receipt — رقم العملية اللي على الصورة متسجّل على طلب تاني.
--                       هاش البايت بيرفض ده وقت الدفع، لكن نفس التحويلة
--                       مصوَّرة صورتين مختلفتين ما بينمسكش غير بالقراية،
--                       والقراية بتحصل بعد الحفظ فما ينفعش ترفض.
--
-- ⚠️ المبلغ اللي ما اتقراش (NULL) ما بيحجزش حاجة. ٩ من ١٠ إيصالات كانوا كده
-- قبل ما القراية تتظبط، وحجزهم كان هيحوّل «محتاجة مراجعة» لقايمة الطلبات كلها.
-- «مقريتش» مش «ناقص».
--
-- ## التنضيف
--
-- أيمن بيقبل الطلب ⇒ `held_for_review_at` يرجع NULL والطلب يرجع للقايمة. مفيش
-- عمود «اتراجع إمتى»: الأوديت بيمسك مين وإمتى، والصف هنا محتاج يجاوب سؤال
-- واحد بس — «هو محجوز دلوقتي ولا لأ».
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE "app"."book_orders"
  ADD COLUMN "held_for_review_at" TIMESTAMP(3),
  ADD COLUMN "held_reason"        TEXT;

-- السبب لازم يبقى واحد من اللي الكود بيعرفه، ولازم يمشي مع الوقت: صف محجوز من
-- غير سبب ما بيقولش للأدمن يبص على إيه، وسبب من غير حجز بيبقى بقايا قرار
-- اتلغى.
ALTER TABLE "app"."book_orders"
  ADD CONSTRAINT "book_orders_held_reason_matches_hold"
  CHECK (
    ("held_for_review_at" IS NULL AND "held_reason" IS NULL)
    OR ("held_for_review_at" IS NOT NULL
        AND "held_reason" IN ('amount_short', 'duplicate_receipt'))
  );

-- الفهرس جزئي منطقياً — المحجوز حفنة والباقي الجدول كله — بس مكتوب كامل عشان
-- `@@index` في الـschema مالوش تعبير عن WHERE، وأي فرق بيفضل يبان في كل
-- `migrate diff` بعد كده.
CREATE INDEX "book_orders_held_for_review_at_idx"
  ON "app"."book_orders" ("held_for_review_at");
