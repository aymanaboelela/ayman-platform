-- «٣ شهور» اتشالت من الرف — السعر بس، مش التاريخ.
--
-- المدرّس قرر يوقّف باقة الـ٣ شهور. اللي بيتشال هنا هو القدرة على البيع، يعني
-- `courses.quarterly_price_cents` بيرجع NULL. اللي مابيتشالش:
--
--   · العمود نفسه. لسه موجود، ولسه `CourseService` بيقرا منه — بس بقى بيرفض
--     أي قيمة مش NULL تتكتب فيه (BadRequest). الشيل الكامل ميجريشن على جدول
--     فيه فلوس حية ومفيش منه فايدة.
--   · قيمة الـenum `quarterly` في `app.payment_plan`. فيه
--     `payment_submissions` و`access_grants` بالمئات شايلينها، وشاشات
--     الفلوس بتقرا منها. ضيّق `PaymentPlanSchema` بدل كده وكل صف قديم
--     هيرمي عند القراية — ده مكتوب بالحرف في هيدر `SellablePaymentPlanSchema`.
--   · الطلبة اللي مشتركين ٣ شهور دلوقتي. الاشتراك بتاعهم grant شغّال بـ
--     `valid_until` بتاعه، والـUPDATE ده مابيلمسش `access_grants` خالص.
--
-- ── الحالة اللي ممكن تحصل، وهي مقصودة ────────────────────────────────────
-- كورس كان سعره الوحيد ٣ شهور بيبقى بعد الميجريشن دي كورس **من غير أي باقة**،
-- و`requires_grant` لسه `true` — يعني مقفول ومحدش يقدر يشتريه. ده مش كسر
-- مستخفي: الكورس بيبان في الأدمن بأسعاره فاضية، وصفحة الكورس بتقول «مش
-- للبيع»، والمدرّس بيصلّحها بحقل سعر واحد (شهري أو سنوي). الحالة التانية —
-- إننا نسيب السعر — معناها زرار «٣ شهور» يفضل على الموقع لباقة مش موجودة.
--
-- ── `courses_priced_requires_grant` ──────────────────────────────────────
--   CHECK ((monthly IS NULL AND quarterly IS NULL AND yearly IS NULL)
--          OR requires_grant)
-- الـUPDATE ده بيحوّل عمود لـNULL وبس. الطرف الأول من الـOR بيبقى أسهل
-- يتحقق، مش أصعب: لو كان بيمرّ قبل الميجريشن هيمرّ بعدها، ولو كان بيمرّ
-- بسبب `requires_grant` فهي ماتغيّرتش. يعني الـCHECK **مستحيل** يتكسر هنا،
-- ومفيش حاجة محتاجة تتعدّل فيه. نفس الكلام على
-- `courses_book_needs_price_and_title` — مالوش علاقة بأسعار الاشتراك أصلًا.
-- ═══════════════════════════════════════════════════════════════════════════

UPDATE "app"."courses"
   SET "quarterly_price_cents" = NULL
 WHERE "quarterly_price_cents" IS NOT NULL;
