-- بصمة إيصال التحويل — «الإيصال الواحد ما يتصرفش مرتين».
--
-- ## الحكاية اللي الملف ده اترفع عشانها
--
-- يوم ١٧/٠٩/٢٠٢٦، وإحنا بنجهّز كروت الشحن، طلع خمس طلبة كل واحد فيهم عنده
-- طلبين مدفوعين لنفس الكتاب:
--
--   احمد محمد ابراهيم  · BK-587D74 + BK-13F450 · بفارق ١١ دقيقة
--   ayasaber            · BK-65F33B + BK-A44CDC · بفارق ٨ دقايق
--   معاذ محمد فوزي      · BK-9B0544 + BK-8C7643 · بفارق دقيقتين
--   Abdelrahman Khaled  · BK-D5AB7C + BK-846854 · بفارق يوم
--   Amar Zaghloul       · BK-EA9B7C + BK-7A3FD3 · بفارق يومين
--
-- الأربعة الأولانيين رفعوا **نفس ملف الصورة بالبايت** على الطلبين — نفس
-- الـSHA-256 ونفس الحجم بالظبط. يعني تحويلة واحدة اتقدّمت مرتين. والخامس
-- (Amar) رفع **صورتين مختلفتين لنفس التحويلة**: وحدة سكرين شوت لرسالة فودافون
-- كاش والتانية إيصال من تطبيق إنستا باي، والاتنين رقم عمليتهم `023031384189`
-- ونفس المبلغ ونفس الرقم المحوَّل له.
--
-- دول مش ناس دفعت مرتين. `BookOrderPanel` بيقرا الطلب اللي لسه شغال من
-- `localStorage`، فلو الطالب فتح من موبايل تاني أو مسح بيانات الموقع، الفورم
-- بيبدأ من الأول ومفيش أي حاجة في السيرفر كانت بتوقفه. نفس العيب اللي
-- `create` اتصلح منه في ١٤/٠٩ للطلبات اللي لسه ما اتدفعتش — بس المدفوعة
-- كانت مستثناة بالنص.
--
-- ## ليه تلات أعمدة مش عمود
--
-- كل واحد بيمسك حاجة التاني ما بيشوفهاش:
--
--   `screenshot_sha256` — نفس الملف بالظبط. ده كان هيمسك أربعة من الخمسة
--     لوحده. المقارنة مساواة، مش تقريب، لأن `gateAndEncode` بيعيد ترميز كل
--     رفع لـwebp — فرفعتين لنفس الملف بيطلعوا نفس البايتات.
--
--   `screenshot_phash` — نفس الصورة بعد قص أو ضغط. بصمة شكلية ٦٤ بت في ١٦
--     حرف hex، بتتقارن بمسافة هامنج. دي **شبهة مش دليل**، عشان كده بتتقارن
--     على طلبات نفس الموبايل بس.
--
--   `screenshot_ref` — رقم العملية نفسه، اللي بيتقري من الصورة. ده الوحيد
--     اللي بيعرّف الفلوس مش صورة الفلوس، وهو الوحيد اللي كان هيمسك Amar.
--
-- و`screenshot_amount_cents` مالوش أي علاقة بالمنع: ده المبلغ المقروء من
-- الصورة، بيتسجّل عشان الأدمن يشوف لو مختلف عن `amount_cents` قبل ما يطبع
-- طرد. الطالب اللي إيصاله مش متقري لازم يقدر يدفع عادي.
--
-- ## كلهم NULLABLE ومفيش UNIQUE
--
-- NULLABLE لأن كل طلب اتعمل قبل الملف ده مالوش بصمة، ولأن الـOCR بيفشل أحياناً
-- وده ناتج طبيعي.
--
-- ومفيش UNIQUE بالذات: المطلوب إن التكرار يترفض برسالة بتقول اسم الطلب اللي
-- اصطدم بيه — «الإيصال ده اتبعت قبل كده على طلب BK-XXXX» — ومخالفة قيد بتوصل
-- ٥٠٠ مفيهاش حاجة الطالب يعملها. القاعدة عايشة في `submitPayment`، والـindex
-- هنا بيخليها رخيصة بس.
--
-- ⚠️ وUNIQUE كان هيبوظ الداتا الموجودة كمان: الأربع أزواج اللي فوق لسه في
-- القاعدة بنفس الصورة، فأي قيد فريد يترفع دلوقتي هيفشل على الفور.
--
-- ## `(phone, status)`
--
-- الفحص التاني — «نفس الطالب وطلبه الأول لسه في السكة» — بيدور بالموبايل مش
-- بالحساب، لأن `user_id` بيفضل NULL في الشراء من غير تسجيل وده أغلب الصفوف.
-- `phone` بيتخزن E.164 بعد `egyptianPhone()`، فدي مساواة على نص مُقنَّن.
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE "app"."book_orders"
  ADD COLUMN "screenshot_sha256"       TEXT,
  ADD COLUMN "screenshot_phash"        TEXT,
  ADD COLUMN "screenshot_ref"          TEXT,
  ADD COLUMN "screenshot_amount_cents" INTEGER;

-- المبلغ المقروء مينفعش يبقى بالسالب. مش بيقارن نفسه بـ`amount_cents` —
-- الاختلاف ده حاجة الأدمن يبصلها، مش حاجة القاعدة ترفضها.
ALTER TABLE "app"."book_orders"
  ADD CONSTRAINT "book_orders_screenshot_amount_not_negative"
  CHECK ("screenshot_amount_cents" IS NULL OR "screenshot_amount_cents" >= 0);

-- ٦٤ بت في ١٦ حرف hex. القيد شكلي بحت: بصمة بطول غلط معناها إن حد كتب في
-- العمود من برّه `perceptualHash`، وساعتها مسافة هامنج بتبقى بتقارن حاجتين
-- مش من نفس النوع وبترجع أرقام مالهاش معنى.
ALTER TABLE "app"."book_orders"
  ADD CONSTRAINT "book_orders_screenshot_phash_is_16_hex"
  CHECK ("screenshot_phash" IS NULL OR "screenshot_phash" ~ '^[0-9a-f]{16}$');

-- SHA-256 = ٦٤ حرف hex، لنفس السبب.
ALTER TABLE "app"."book_orders"
  ADD CONSTRAINT "book_orders_screenshot_sha256_is_64_hex"
  CHECK ("screenshot_sha256" IS NULL OR "screenshot_sha256" ~ '^[0-9a-f]{64}$');

-- ⚠️ indexes كاملة مش جزئية، رغم إن أغلب الصفوف النهاردة `NULL` وما بتتدوَّرش.
-- `@@index` في `schema.prisma` مالوش تعبير عن `WHERE`، فأي index جزئي هنا
-- بيبقى فرق بين الملف والـschema يفضل يظهر في كل `migrate diff` بعد كده.
-- الجدول ٢٢٩ صف، فالفرق في الحجم ما يستاهلش الفرق الدايم ده.
CREATE INDEX "book_orders_screenshot_sha256_idx"
  ON "app"."book_orders" ("screenshot_sha256");

CREATE INDEX "book_orders_screenshot_ref_idx"
  ON "app"."book_orders" ("screenshot_ref");

CREATE INDEX "book_orders_phone_status_idx"
  ON "app"."book_orders" ("phone", "status");
