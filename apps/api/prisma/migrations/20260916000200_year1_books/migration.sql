-- كتابين أولى بكالوريا — واحد عربي وواحد لغات — على الرف.
--
-- «هنضيف كتابين، واحد سنة أولى سنوي عربي وواحد سنة أولى لغات. يبقى الكورس لما
--  واحد يشترك فيه يلاقي الكتاب قدامه زي تانية، وبرضه موجود برا في الـhome page.»
--
-- ## ليه migration مش إدخال من لوحة الإدارة
--
-- عشان الصفين يبقوا نفس الحاجة على كل داتابيز: الـstaging، وأي checkout جديد،
-- والإنتاج. كتب تانية بكالوريا اتكتبت بالإيد على الإنتاج لوحده، ونتيجتها إن
-- أي حد بيقوم بالمشروع من الصفر بيلاقي المتجر فاضي ومحتار هو ناقصه data ولا
-- ناقصه كود. ده بيقفل الفرق.
--
-- ## ليه `is_active = true` هنا، وهو ممنوع في الـbackfill
--
-- تحذير `Book.isActive` مكتوب عن الاستيراد: `20260902120000_book_catalog` خد
-- `courses.book_title` على إنه اسم كتاب، وهو على الإنتاج كان جملة إعلانية
-- («حجز الكتاب هيتبعتلك لحد البيت»)، فالمتجر فتح وهو بيبيع الجملة دي بـ٢٥٠ ج.
-- القاعدة اللي طلعت من ده: ما تنشرش قيمة إنت ما اخترتهاش.
--
-- الأسامي والسعر تحت مش مستوردين من أي عمود — مكتوبين بالإيد، على نفس نمط
-- كتابين تانية بكالوريا اللي على الإنتاج دلوقتي («كتاب تانية بكالوريا برمجة
-- عربي» / «… لغات»، ٢٥٠ ج للاتنين، `shipping_cents = 0`)، وبطلب صريح إنهم
-- يبانوا في المتجر وعلى الصفحة الرئيسية وعلى صفحة الكورس. فمفيش تخمين يتنشر.
--
-- ## الترم `full`
--
-- «سنوي» — الكتاب بيغطي السنة كلها. كتب تانية بكالوريا `first` لأنها ترم أول
-- فعلاً، والاتنين بيقعدوا في رفّين مختلفين في `/books` وده صح.
--
-- ## الغلاف
--
-- بياخد `cover_key` بتاع الكورس نفسه. مش الغلاف النهائي للكتاب — أول ما يترفع
-- غلاف حقيقي من لوحة الإدارة هيستبدله — بس كارت من غير صورة في المتجر بيبان
-- مكسور، وصورة الكورس هي أقرب صورة صح موجودة.
--
-- ## ليه INSERT … SELECT وليه idempotent
--
-- الـid بتاع الكورس مختلف على كل داتابيز، فالربط بيتعمل بالـslug. و
-- `WHERE NOT EXISTS` + `ON CONFLICT DO NOTHING` عشان الملف ده يعدّي من غير
-- ضرر على أي داتابيز الكتب فيها اتضافت بالإيد قبل ما ده يوصل — `books.course_id`
-- UNIQUE، والتصادم ده احتمال حقيقي مش نظري.
--
-- ⚠️ مفيش لمس لـ`courses.book_title` / `book_price_cents`. الصف في الكتالوج بقى
-- هو المصدر (شوف `courseBook()`): أول ما يبقى `is_active` الكورس بيقرأ منه،
-- والعمودين القدام بيفضلوا فاضيين زي ما هم بدل ما نكتب نسخة تانية من نفس السعر
-- تروح تعتّق.
-- ═══════════════════════════════════════════════════════════════════════════

INSERT INTO "app"."books" (
    "id", "slug", "title_ar", "subject_id", "year", "term", "course_id",
    "price_cents", "cover_key",
    "for_general", "for_languages",
    "show_on_landing", "show_on_course",
    "is_active", "sort_order", "created_at", "updated_at"
)
SELECT
    gen_random_uuid(),
    c."slug",
    CASE WHEN c."for_languages"
         THEN 'كتاب أولى بكالوريا برمجة لغات'
         ELSE 'كتاب أولى بكالوريا برمجة عربي'
    END,
    c."subject_id",
    c."year",
    'full'::"app"."book_term",
    c."id",
    -- ٢٥٠ ج، زي كتابين تانية بكالوريا بالظبط.
    25000,
    c."cover_key",
    -- الطبعة خاصية الورق نفسه، فبتتاخد من الكورس اللي هي طبعته — مش `true`
    -- للاتنين، وإلا الكتاب العربي هيبان لطالب لغات والعكس.
    c."for_general",
    c."for_languages",
    true,
    true,
    true,
    0,
    now(),
    now()
FROM "app"."courses" c
WHERE c."slug" IN ('programming-cs-year1-2027-general', 'programming-cs-year1-2027-languages')
  AND NOT EXISTS (SELECT 1 FROM "app"."books" b WHERE b."course_id" = c."id")
  AND NOT EXISTS (SELECT 1 FROM "app"."books" b WHERE b."slug" = c."slug")
ON CONFLICT DO NOTHING;
